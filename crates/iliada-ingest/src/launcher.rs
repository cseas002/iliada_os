//! Entry points: the host-side launcher script.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use iliada_bundle::BundleLayout;

/// Write `Contents/Executables/<name>`, a POSIX sh launcher that makes the
/// bundled libraries visible to the dynamic loader and execs the real binary.
///
/// This is the *host-side* view (development and Tier-1 sandboxes). In a
/// Tier-2 micro-VM, `Contents/Root` is mounted at `/` and `Contents/Libraries`
/// is appended to the loader path by the guest image, so the same bundle runs
/// unchanged.
pub fn write_launcher(
    layout: &BundleLayout,
    name: &str,
    exe_in_root: &Path,
    args: &[String],
    triplet: Option<&str>,
) -> Result<PathBuf> {
    let mut lib_path = vec!["$here/Libraries".to_owned()];
    if let Some(t) = triplet {
        lib_path.push(format!("$here/Root/usr/lib/{t}"));
        lib_path.push(format!("$here/Root/lib/{t}"));
    }
    lib_path.push("$here/Root/usr/lib".to_owned());
    let script = format!(
        "#!/bin/sh\n\
         # Generated by iliada-ingest. Host-side launcher; see Contents/Info.toml.\n\
         here=\"$(cd \"$(dirname \"$0\")/..\" && pwd)\"\n\
         export LD_LIBRARY_PATH=\"{}${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}\"\n\
         export XDG_DATA_DIRS=\"$here/Root/usr/share:${{XDG_DATA_DIRS:-/usr/local/share:/usr/share}}\"\n\
         [ -f \"$here/Root/usr/share/glib-2.0/schemas/gschemas.compiled\" ] && export GSETTINGS_SCHEMA_DIR=\"$here/Root/usr/share/glib-2.0/schemas\"\n\
         exec \"$here/Root/{}\"{} \"$@\"\n",
        lib_path.join(":"),
        exe_in_root.display(),
        args.iter().map(|a| format!(" '{}'", a.replace('\'', "'\\''"))).collect::<String>()
    );
    let path = layout.executables().join(name);
    fs::write(&path, script).with_context(|| format!("writing {}", path.display()))?;
    fs::set_permissions(&path, fs::Permissions::from_mode(0o755))?;
    Ok(path)
}

pub(crate) fn which(bin: &str) -> Result<PathBuf> {
    let path = std::env::var_os("PATH").context("PATH unset")?;
    std::env::split_paths(&path).map(|d| d.join(bin)).find(|p| p.is_file()).context("not found")
}
