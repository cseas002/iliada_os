//! Entry points: a launcher script, plus optional RUNPATH rewriting.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use iliada_bundle::BundleLayout;

/// Write `Contents/Executables/<name>`, a POSIX sh launcher that makes the
/// bundled libraries visible to the dynamic loader and execs the real binary.
///
/// This is the *host-side* view (development and Tier-1 sandboxes). In a
/// Tier-2 micro-VM, `Contents/Root` is mounted at `/` and `Contents/Libraries`
/// is appended to the loader path by the guest image, so the same bundle runs
/// unchanged.
pub fn write_launcher(layout: &BundleLayout, name: &str, exe_in_root: &Path, triplet: Option<&str>) -> Result<PathBuf> {
    let mut lib_path = vec!["$here/Libraries".to_owned()];
    if let Some(t) = triplet {
        lib_path.push(format!("$here/Root/usr/lib/{t}"));
        lib_path.push(format!("$here/Root/lib/{t}"));
    }
    lib_path.push("$here/Root/usr/lib".to_owned());
    let script = format!(
        "#!/bin/sh\n\
         # Generated by iliada-ingest. Host-side launcher; see Contents/Info.toml.\n\
         here=\"$(cd \"$(dirname \"$0\")/..\" && pwd)\"\n\
         export LD_LIBRARY_PATH=\"{}${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}\"\n\
         exec \"$here/Root/{}\" \"$@\"\n",
        lib_path.join(":"),
        exe_in_root.display()
    );
    let path = layout.executables().join(name);
    fs::write(&path, script).with_context(|| format!("writing {}", path.display()))?;
    fs::set_permissions(&path, fs::Permissions::from_mode(0o755))?;
    Ok(path)
}

/// If `patchelf` is installed, point each executable's RUNPATH at the bundled
/// libraries using `$ORIGIN`, so the binary also works without the launcher.
/// Returns how many files were patched (0 when patchelf is absent).
pub async fn patch_runpaths(layout: &BundleLayout, executables: &[PathBuf], triplet: Option<&str>) -> Result<usize> {
    let Ok(patchelf) = which("patchelf") else {
        tracing::info!("patchelf not found; relying on the launcher's LD_LIBRARY_PATH");
        return Ok(0);
    };
    let mut n = 0;
    for rel in executables {
        // Number of directories between the binary and Contents/.
        let depth = rel.parent().map(|p| p.components().count()).unwrap_or(0) + 1;
        let up = "../".repeat(depth);
        let mut rpath = vec![format!("$ORIGIN/{up}Libraries")];
        if let Some(t) = triplet {
            rpath.push(format!("$ORIGIN/{up}Root/usr/lib/{t}"));
        }
        let file = layout.fhs_root().join(rel);
        let status =
            tokio::process::Command::new(&patchelf).arg("--set-rpath").arg(rpath.join(":")).arg(&file).status().await?;
        if status.success() {
            n += 1;
        } else {
            tracing::warn!(file = %file.display(), "patchelf failed; launcher fallback still applies");
        }
    }
    Ok(n)
}

fn which(bin: &str) -> Result<PathBuf> {
    let path = std::env::var_os("PATH").context("PATH unset")?;
    std::env::split_paths(&path).map(|d| d.join(bin)).find(|p| p.is_file()).context("not found")
}
